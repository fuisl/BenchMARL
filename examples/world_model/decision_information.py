"""Gate 0d: localise where decision information is lost.

The architecture and dynamics checkpoints are frozen.  One shared candidate
bank is scored through:

 A. simulator truth;
 B. true trajectory -> encoder -> existing reward/termination readout;
 C. predicted latent trajectory -> existing reward/termination readout;
 D. predicted latent trajectory -> task-sufficient diagnostic head.

The same comparisons are repeated on every candidate population generated by
the existing reward-head CEM planner.  Diagnostic heads are the only fitted
components; they never update the encoder, transition, or existing readout.
"""

